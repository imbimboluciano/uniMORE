SELECT AA,CLASSE, NISCR=count(*)  
FROM ISCRIZIONI  
GROUP BY AA, CLASSE WITH ROLLUP

-- L'ordine è rilevante (seguire il verso opposto della gerarchia)
-- Realizzazione del pattern {A1, A2, …, Ak} e dei seguenti k sottoinsiemi    {A1, A2, …, Ak-1 } , {A1, A2, …, Ak-2 }  …     {A1}     {}

SELECT		  
CLASSE=CASE WHEN GROUPING(CLASSE)=1 THEN 'TuttiLeClassi'
		 ELSE CLASSE END,
TIPO=CASE WHEN GROUPING(CLASSE)=1 THEN 'TuttiITipi'
		 ELSE TIPO END,
  NISCR=count(*),
  GROUPING(CLASSE) AS AGGREGO_CLASSE,
  GROUPING_ID(CLASSE,TIPO) AS PATTERN
FROM ISCRIZIONI  
GROUP BY TIPO,CLASSE WITH ROLLUP

