-- Proviamo anche GROUPING SETS, nel quale dobbiamo esplicitare tutti i pattern validi
-- Non è possibile creare combinazioni di CUBE e ROLLUP
-- Non genera i pattern superflui
SELECT AA, CDL, TIPO, NISCR = COUNT(*)
FROM ISCRIZIONI 
GROUP BY
    GROUPING SETS (
        (AA, CDL),
        (AA, TIPO),
        (AA),
        (CDL),
        (TIPO),
        ()
    );

