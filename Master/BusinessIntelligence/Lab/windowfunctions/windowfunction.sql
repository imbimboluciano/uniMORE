-- RANKING
CREATE VIEW AZIENDA_DIPARTIMENTO AS
SELECT AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO, NUMORE = SUM(NumORE)
FROM FACT_TABLE
GROUP BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO

CREATE VIEW V1 AS 
SELECT	AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,NUMORE,
		SUM(NumORE) OVER (PARTITION BY DIPARTIMENTO_UFFICIO) AS TotaleOrePerDipartimento,
		ROW_NUMBER() OVER (PARTITION BY DIPARTIMENTO_UFFICIO ORDER BY NUMORE DESC) AS [RANK], 
FROM AZIENDA_DIPARTIMENTO

SELECT *, CAST(NUMORE AS REAL) / TotaleOrePerDipartimento AS Rapporto
FROM V1 
WHERE [RANK] = 1

