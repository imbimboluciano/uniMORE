CREATE VIEW DATA_AZIENDA_DIPARTIMENTO AS
SELECT DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO, NumORE= SUM(NumORE)
FROM FACT_TABLE
GROUP BY DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO


SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO) AS TotaleAziendaDipartimento,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO ORDER BY DATA) AS TotaleAziendaDipartimentoPerData
FROM DATA_AZIENDA_DIPARTIMENTO


