SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,NumORE,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER() AS GranTotal
