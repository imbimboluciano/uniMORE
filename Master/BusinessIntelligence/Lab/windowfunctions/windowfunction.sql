SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,NumORE,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER() AS GranTotal,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE ORDER BY DATA) AS TotaleAziendaPerData,
		SUM(NumORE) OVER(ORDER BY DATA) AS GranTotalPerData
FROM FACT_TABLE

-- ROWS UNBOUNDED PRECEDING: considera illimitatamente le righe precedenti nella finestra
SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,NumORE,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER() AS GranTotal,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE ORDER BY DATA) AS TotaleAziendaPerData,
		SUM(NumORE) OVER(ORDER BY DATA) AS GranTotalPerData,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE ORDER BY DATA ROWS UNBOUNDED PRECEDING) AS TotaleAziendaPerDataU,
		SUM(NumORE) OVER(ORDER BY DATA ROWS UNBOUNDED PRECEDING) AS GranTotalPerDataU
FROM FACT_TABLE


SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,NumORE,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO) AS TotaleAziendaDipartimento
FROM FACT_TABLE

SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,NumORE,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO) AS TotaleAziendaDipartimento,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO ORDER BY DATA) AS TotaleAziendaDipartimentoPerData
FROM FACT_TABLE

SELECT  DATA, AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO,SUM(NumORE) AS NumORE
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE) AS TotalePerAzienda,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO) AS TotaleAziendaDipartimento,
		SUM(NumORE) OVER(PARTITION BY AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO ORDER BY DATA) AS TotaleAziendaDipartimentoPerData
FROM FACT_TABLE
GROUP BY DATA,AZIENDA_PERSONALE, DIPARTIMENTO_UFFICIO

