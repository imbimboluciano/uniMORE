-- Creazione delle tabelle

CREATE TABLE CITTÀ (
    CITTÀ VARCHAR(50) PRIMARY KEY,
    STATO VARCHAR(50)
);

CREATE TABLE AEROPORTO (
    AEROPORTO VARCHAR(50) PRIMARY KEY,
    CITTÀ VARCHAR(50),
    CATEGORIA VARCHAR(20),
    FOREIGN KEY (CITTÀ) REFERENCES CITTÀ(CITTÀ)
);

CREATE TABLE PERSONA (
    PERSONA VARCHAR(50) PRIMARY KEY,
    RESIDENZA VARCHAR(50),
    FOREIGN KEY (RESIDENZA) REFERENCES CITTÀ(CITTÀ)
);

CREATE TABLE BIGLIETTO (
    BIGLIETTO VARCHAR(50) PRIMARY KEY,
    AGENZIA VARCHAR(50),
    COSTO DECIMAL(10,2),
    PERSONA VARCHAR(50),
    FOREIGN KEY (PERSONA) REFERENCES PERSONA(PERSONA)
);

CREATE TABLE BOARDING_PASS (
    BIGLIETTO VARCHAR(50),
    PARTENZA VARCHAR(50),
    DESTINAZIONE VARCHAR(50),
    COMPAGNIA_AEREA VARCHAR(50),
    DURATA INT,
    FOREIGN KEY (BIGLIETTO) REFERENCES BIGLIETTO(BIGLIETTO),
    FOREIGN KEY (PARTENZA) REFERENCES AEROPORTO(AEROPORTO),
    FOREIGN KEY (DESTINAZIONE) REFERENCES AEROPORTO(AEROPORTO)
);






