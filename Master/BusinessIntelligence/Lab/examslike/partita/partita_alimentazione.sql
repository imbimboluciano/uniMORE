-- DIMENSION TABLE SQUADRA_FUORI
CREATE VIEW DT_SQUADRA_FUORI AS
SELECT 
    SQUADRA_FUORI.SQUADRA AS SQUADRA_FUORI, 
    SQUADRA_FUORI.CITTA AS SQUADRA_FUORI_CITTA, 
    COALESCE(SQUADRA_FUORI_PRESIDENTE.PRESIDENTE,'NO_PRESIDENTE') AS SQUADRA_FUORI_PRESIDENTE, 
    COALESCE(SQUADRA_FUORI_PRESIDENTE.CITTA,'NO_PRESIDENTE') AS SQUADRA_FUORI_PRESIDENTE_CITTA
FROM dbo.PRESIDENTE AS SQUADRA_FUORI_PRESIDENTE
RIGHT JOIN dbo.SQUADRA AS SQUADRA_FUORI 
    ON SQUADRA_FUORI_PRESIDENTE.PRESIDENTE = SQUADRA_FUORI.PRESIDENTE;

SELECT COUNT(*) FROM SQUADRA
SELECT COUNT(*) FROM DT_SQUADRA_FUORI

-- DIMENSION TABLE TOP_PLAYER
ALTER VIEW DT_TOP_PLAYER AS
SELECT 
    TOP_PLAYER.GIOCATORE AS TOP_PLAYER_GIOCATORE, 
    TOP_PLAYER.RUOLO AS TOP_PLAYER_RUOLO, 
    TOP_PLAYER_SQUADRA.SQUADRA AS TOP_PLAYER_SQUADRA, 
    TOP_PLAYER_SQUADRA.CITTA AS TOP_PLAYER_SQUADRA_CITTA,
	COALESCE(TOP_PLAYER_SQUADRA_PRESIDENTE.PRESIDENTE,'NO_PRESIDENTE') AS TOP_PLAYER_SQUADRA_PRESIDENTE, 
    COALESCE(TOP_PLAYER_SQUADRA_PRESIDENTE.CITTA,'NO_PRESIDENTE') AS TOP_PLAYER_SQUADRA_PRESIDENTE_CITTA
FROM dbo.GIOCATORE AS TOP_PLAYER
INNER JOIN dbo.SQUADRA AS TOP_PLAYER_SQUADRA 
    ON TOP_PLAYER.SQUADRA = TOP_PLAYER_SQUADRA.SQUADRA
LEFT JOIN dbo.PRESIDENTE AS TOP_PLAYER_SQUADRA_PRESIDENTE 
    ON TOP_PLAYER_SQUADRA.PRESIDENTE = TOP_PLAYER_SQUADRA_PRESIDENTE.PRESIDENTE
UNION
SELECT 'NO_TOP_PLAYER','NO_TOP_PLAYER','NO_TOP_PLAYER','NO_TOP_PLAYER','NO_TOP_PLAYER','NO_TOP_PLAYER'


SELECT COUNT(*) FROM DT_TOP_PLAYER
