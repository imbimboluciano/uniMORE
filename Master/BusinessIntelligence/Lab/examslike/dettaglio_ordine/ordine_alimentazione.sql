-- DIMENSION TABLE AZIENDA
-- FORMATTA CON CHATGPT
CREATE VIEW DT_AZIENDA AS
SELECT dbo.AZIENDA.AZIENDA, dbo.CITTA.CITTA AS CITTA_AZIENDA, dbo.CITTA.REGIONE AS REGIONE_AZIENDA
FROM     dbo.AZIENDA INNER JOIN
                  dbo.CITTA ON dbo.AZIENDA.CITTA = dbo.CITTA.CITTA


-- DIMENSION TABLE CLIENTE
-- FORMATTA CON CHATGPT
CREATE VIEW DT_CLIENTE AS
SELECT dbo.CLIENTE.CLIENTE, dbo.CITTA.CITTA AS CITTA_CLIENTE, dbo.CITTA.REGIONE AS REGIONE_CLIENTE, dbo.PRODOTTO.PRODOTTO AS PREFERENZA, dbo.AZIENDA.AZIENDA AS CLIENTE_AZIENDA, CITTA_1.CITTA AS CLIENTE_CITTA_AZIENDA, 
                  CITTA_1.REGIONE AS CLIENTE_REGIONE_AZIENDA
FROM     dbo.PRODOTTO INNER JOIN
                  dbo.AZIENDA ON dbo.PRODOTTO.AZIENDA = dbo.AZIENDA.AZIENDA INNER JOIN
                  dbo.CLIENTE INNER JOIN
                  dbo.CITTA ON dbo.CLIENTE.CITTA = dbo.CITTA.CITTA ON dbo.PRODOTTO.PRODOTTO = dbo.CLIENTE.PREFER INNER JOIN
                  dbo.CITTA AS CITTA_1 ON dbo.AZIENDA.CITTA = CITTA_1.CITTA

SELECT COUNT(*) FROM CLIENTE
SELECT COUNT(*) FROM DT_CLIENTE


