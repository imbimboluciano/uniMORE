-- VISTA DI APPOGGIO

CREATE VIEW PER_FT AS
SELECT dbo.PRODOTTO.AZIENDA, dbo.ORDINE.CLIENTE, dbo.ORDINE.DATA_ORDINE, dbo.DETTAGLIO.DATA_SPED, dbo.DETTAGLIO.COSTO, dbo.PRODOTTO.PRODOTTO, dbo.ORDINE.ORDINE
FROM     dbo.DETTAGLIO INNER JOIN
                  dbo.ORDINE ON dbo.DETTAGLIO.ORDINE = dbo.ORDINE.ORDINE INNER JOIN
                  dbo.PRODOTTO ON dbo.DETTAGLIO.PRODOTTO = dbo.PRODOTTO.PRODOTTO

SELECT COUNT(*) FROM PER_FT
SELECT COUNT(*) FROM DETTAGLIO

-- FT

CREATE VIEW FACT_TABLE AS
SELECT	CLIENTE, AZIENDA, DATA_ORDINE, DATA_SPED, 
		NUMPROD=COUNT(DISTINCT PRODOTTO), NUMSPED=COUNT(*),
		COSTO=SUM(COSTO), NUMORD=COUNT(DISTINCT ORDINE)
FROM PER_FT
GROUP BY CLIENTE, AZIENDA, DATA_ORDINE, DATA_SPED



ALTER VIEW STAR_SCHEMA AS
SELECT  RITARDO = DATEDIFF(DAY, DATA_ORDINE, DATA_SPED), dbo.FACT_TABLE.DATA_ORDINE, dbo.FACT_TABLE.DATA_SPED, dbo.FACT_TABLE.NUMPROD, dbo.FACT_TABLE.NUMSPED, dbo.FACT_TABLE.COSTO, dbo.FACT_TABLE.NUMORD, dbo.DT_CLIENTE.*, dbo.DT_AZIENDA.*
FROM     dbo.FACT_TABLE INNER JOIN
                  dbo.DT_CLIENTE ON dbo.FACT_TABLE.CLIENTE = dbo.DT_CLIENTE.CLIENTE INNER JOIN
                  dbo.DT_AZIENDA ON dbo.FACT_TABLE.AZIENDA = dbo.DT_AZIENDA.AZIENDA


