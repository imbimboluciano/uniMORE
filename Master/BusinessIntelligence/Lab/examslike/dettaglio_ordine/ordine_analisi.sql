CREATE VIEW CUBE_SETTORE_DATA_ordine AS
SELECT	PATTERN=GROUPING_id( SETTORE, DATA_ORDINE ),
		SETTORE = CASE WHEN GROUPING(SETTORE) = 0 THEN SETTORE ELSE 'ALL_SETTORE' END,
		DATA_ORDINE = CASE WHEN GROUPING(DATA_ORDINE) = 0 THEN DATA_ORDINE ELSE '1999-09-19' END,
		-- MISURE
		NUMSPED = CASE WHEN GROUPING(SETTORE) = 1 THEN SUM(NUMSPED_PES) ELSE SUM(NUMSPED) END,
		COSTO=SUM(COSTO_PES)
FROM STAR_SCHEMA_PD
GROUP BY SETTORE, DATA_ORDINE WITH CUBE

