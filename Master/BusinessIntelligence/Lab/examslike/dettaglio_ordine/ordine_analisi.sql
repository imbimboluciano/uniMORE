	ROW_NUMBER() OVER (PARTITION BY CLIENTE, YEAR(DATA_SPED) ORDER BY NUMSPED DESC) AS RowNo
FROM PATTERN_CLIENTE_DATA_SPED

SELECT * FROM TOP_2_CLIENTE_ANNO
