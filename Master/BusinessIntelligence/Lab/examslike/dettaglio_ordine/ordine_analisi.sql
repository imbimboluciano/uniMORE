-- WINDOW FUNCTION
-- spedizioni con un COSTO_maggiore di quello medio per CLIENTE_CITTA

WITH SPED_MAGGIORI_MEDIO_CITTA AS
(
SELECT	CITTA_CLIENTE, COSTO,
		MEDIOCITTA = AVG(COSTO) OVER (PARTITION BY CITTA_CLIENTE) 
FROM STAR_SCHEMA
)
SELECT *
FROM SPED_MAGGIORI_MEDIO_CITTA
WHERE COSTO > MEDIOCITTA



-- per ogni AZIENDA_CITTA il CLIENTE con il maggior numero di spedizioni complessivo

WITH CLIENTE_SPEDIZIONI AS
(
SELECT	CITTA_AZIENDA,CLIENTE,
		TOTALESPED = SUM(NUMSPED)
FROM STAR_SCHEMA
GROUP BY CITTA_AZIENDA,CLIENTE
), CLIENTE_SPEDIZIONI_RANKED AS
(
SELECT *,  [RANK] =  RANK() OVER (PARTITION BY CITTA_AZIENDA ORDER BY TOTALESPED DESC)
FROM CLIENTE_SPEDIZIONI
)
SELECT * 
FROM CLIENTE_SPEDIZIONI_RANKED
WHERE [RANK] = 1


-- WITH CUBE

WITH CLIENTE_SPEDIZIONI AS
(
SELECT	CITTA_AZIENDA,CLIENTE,
		TOTALESPED = SUM(NUMSPED)
FROM STAR_SCHEMA
GROUP BY CITTA_AZIENDA,CLIENTE WITH CUBE
), CLIENTE_SPEDIZIONI_RANKED AS
(
SELECT *,  [RANK] =  RANK() OVER (PARTITION BY CITTA_AZIENDA ORDER BY TOTALESPED DESC)
FROM CLIENTE_SPEDIZIONI
)
SELECT * 
FROM CLIENTE_SPEDIZIONI_RANKED
WHERE [RANK] <= 2 AND CITTA_AZIENDA IS NOT NULL AND CLIENTE IS NOT NULL


-- RITARDO
SELECT AZIENDA, DATA_ORDINE, DATA_SPED,
		MAX_RITARDO = MAX(RITARDO) OVER (PARTITION BY AZIENDA) 
FROM STAR_SCHEMA

-- Ora consideriamo per ogni AZIENDA il mese della DATA_ORDINE e calcoliamo la somma dei ritardi

SELECT	AZIENDA, YEAR(DATA_SPED) AS ANNO, MONTH(DATA_SPED) AS MESE,
		SUM(DATEDIFF(DAY, DATA_ORDINE, DATA_SPED)) AS SOMMA_RITARDI
FROM STAR_SCHEMA
GROUP BY AZIENDA, YEAR(DATA_SPED), MONTH(DATA_SPED)


SELECT	AZIENDA, MONTH(DATA_SPED) AS MESE,
		SUM(DATEDIFF(DAY, DATA_ORDINE, DATA_SPED)) AS SOMMA_RITARDI
FROM STAR_SCHEMA
GROUP BY AZIENDA, MONTH(DATA_SPED)



SELECT	AZIENDA, DATA_ORDINE, DATA_SPED, 
		DATEDIFF(DAY, DATA_ORDINE, DATA_SPED) AS RITARDO, MONTH(DATA_SPED) AS MESE,
		SUM(DATEDIFF(DAY, DATA_ORDINE, DATA_SPED)) OVER (PARTITION BY AZIENDA, MONTH(DATA_SPED)) AS SOMMA_RITARDI_MENSILI
FROM STAR_SCHEMA
ORDER BY AZIENDA, MESE


-- PATTERN CLIENTE, DATA_SPED

CREATE VIEW PATTERN_CLIENTE_DATA_SPED AS
SELECT	CLIENTE, DATA_SPED,
		-- MISURE : per semplicità si considerano sol le misure additive
		NUMSPED=SUM(NUMSPED), COSTO=SUM(COSTO)
FROM STAR_SCHEMA
GROUP BY CLIENTE, DATA_SPED


-- si analizza usando la PARTITION CLIENTE, ANNO_SPED= YEAR(DATA_SPED)

SELECT	CLIENTE, DATA_SPED, YEAR(DATA_SPED) as ANNO_SPED, NUMSPED,
		ROW_NUMBER() OVER (PARTITION BY CLIENTE, YEAR(DATA_SPED) ORDER BY NUMSPED DESC) AS RowNo
FROM PATTERN_CLIENTE_DATA_SPED


-- TOP 2 per cliente anno

CREATE VIEW TOP_2_CLIENTE_ANNO AS
