-- FACT TABLE PUSHDOWN
CREATE VIEW FACT_TABLE_PD AS
SELECT	dbo.INVESTE.FONDO, dbo.FACT_TABLE.DATA, dbo.FACT_TABLE.BANCA_ESTERA, dbo.FACT_TABLE.A_BANCA, dbo.FACT_TABLE.DA_CONTO,
		IMPORTO_SOMMA_P = PESO * IMPORTO_SOMMA,
		COUNT_IMPORTO_P = PESO * COUNT_IMPORTO,
		NUM_A_CONTO_P = PESO * NUM_A_CONTO,
		NUM_A_CONTO
FROM     dbo.FACT_TABLE INNER JOIN
                  dbo.INVESTE ON dbo.FACT_TABLE.DA_CONTO = dbo.INVESTE.CONTO


