-- VISTA APPOGGIO
ALTER VIEW PER_FT AS
SELECT dbo.DOCENZA.AA, dbo.DOCENZA.COD_INS, dbo.DOCENZA.CFU, COALESCE(dbo.ESERCITAZIONI.COD_LAB,'NO_LAB') AS COD_LAB, dbo.DOCENZA.CF_TITOLARE, dbo.ESERCITAZIONI.CF_ESERCITATORE, dbo.INSEGNAMENTO.COD_CDL AS COD_CDL_INSEGNAMENTO, 
                  COALESCE(dbo.DOCENTE.COD_CDL,'NO_CDL') AS COD_CDL_ESERCITATORE
FROM     dbo.ESERCITAZIONI INNER JOIN 
                  dbo.LABORATORIO ON dbo.ESERCITAZIONI.COD_LAB = dbo.LABORATORIO.LAB INNER JOIN
                  dbo.DOCENTE ON dbo.LABORATORIO.CF_RESPONSABILE = dbo.DOCENTE.CF RIGHT OUTER JOIN
                  dbo.DOCENZA INNER JOIN
                  dbo.INSEGNAMENTO ON dbo.DOCENZA.COD_INS = dbo.INSEGNAMENTO.COD_INS ON dbo.ESERCITAZIONI.AA = dbo.DOCENZA.AA AND dbo.ESERCITAZIONI.COD_INS = dbo.DOCENZA.COD_INS

SELECT COUNT(*) FROM PER_FT
