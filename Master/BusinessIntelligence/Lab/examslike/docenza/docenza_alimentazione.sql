

-- DIMENSION TABLE DT_DOCENTE
ALTER VIEW DT_DOCENTE AS
SELECT 
    dbo.DOCENTE.CF AS DOCENTE,
    dbo.DOCENTE.RUOLO AS DOCENTE_RUOLO,
    DOCENTE_CDL.CDL AS DOCENTE_CDL,
    DOCENTE_CDL.TIPO AS DOCENTE_CDL_TIPO,
    DOCENTE_CITTA.CITTA AS DOCENTE_CITTA,
    DOCENTE_CITTA.REGIONE AS DOCENTE_CITTA_REGIONE,
    COALESCE(dbo.RICERCATORE.ETA,-1) AS DOCENTE_ETA
FROM dbo.DOCENTE
INNER JOIN dbo.CORSODILAUREA AS DOCENTE_CDL 
    ON dbo.DOCENTE.COD_CDL = DOCENTE_CDL.CDL
INNER JOIN dbo.CITTA AS DOCENTE_CITTA 
    ON dbo.DOCENTE.RESIDENZA = DOCENTE_CITTA.CITTA
LEFT OUTER JOIN dbo.RICERCATORE 
    ON dbo.DOCENTE.CF = dbo.RICERCATORE.CF;

SELECT COUNT(*) FROM DOCENTE
