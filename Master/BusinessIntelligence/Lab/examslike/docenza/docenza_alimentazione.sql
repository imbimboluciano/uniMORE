-- DIMENSION TABLE COD_LAB
ALTER VIEW DT_COD_LAB AS
SELECT 
    LABORATORIO.LAB AS LABORATORIO,
    LABORATORIO_DIPARTIMENTO.DIP AS LABORATORIO_DIPARTIMENTO,
    RESPONSABILE.CF AS RESPONSABILE,
    RESPONSABILE.NOME AS RESPONSABILE_NOME,
    RESPONSABILE.RUOLO AS RESPONSABILE_RUOLO,
    COALESCE(RESPONSABILE_RICERCATORE.ETA,-1) AS RESPONSABILE_ETA,
    LABORATORIO_DIPARTIMENTO_CITTA.CITTA AS DIPARTIMENTO_CITTA,
    LABORATORIO_DIPARTIMENTO_CITTA.REGIONE AS DIPARTIMENTO_CITTA_REGIONE,
    DIRETTORE.CF AS DIRETTORE,
    DIRETTORE.NOME AS DIRETTORE_NOME,
    DIRETTORE.RUOLO AS DIRETTORE_RUOLO,
    DIRETTORE_CDL.CDL AS DIRETTORE_CDL,
    DIRETTORE_CDL.TIPO AS DIRETTORE_CDL_TIPO,
    COALESCE(DIRETTORE_RICERCATORE.ETA,-1) AS DIRETTORE_ETA,
    DIRETTORE_CITTA.CITTA AS DIRETTORE_CITTA,
    DIRETTORE_CITTA.REGIONE AS DIRETTORE_CITTA_REGIONE,
    RESPONSABILE_CITTA.CITTA AS RESPONSABILE_CITTA,
    RESPONSABILE_CITTA.REGIONE AS RESPONSABILE_CITTA_REGIONE,
    RESPONSABILE_CDL.CDL AS RESPONSABILE_CDL,
    RESPONSABILE_CDL.TIPO AS RESPONSABILE_TIPO
FROM dbo.LABORATORIO
INNER JOIN dbo.DIPARTIMENTO AS LABORATORIO_DIPARTIMENTO 
    ON dbo.LABORATORIO.COD_DIP = LABORATORIO_DIPARTIMENTO.DIP
INNER JOIN dbo.DOCENTE AS RESPONSABILE 
    ON dbo.LABORATORIO.CF_RESPONSABILE = RESPONSABILE.CF
INNER JOIN dbo.CITTA AS LABORATORIO_DIPARTIMENTO_CITTA 
    ON LABORATORIO_DIPARTIMENTO.SEDE = LABORATORIO_DIPARTIMENTO_CITTA.CITTA
INNER JOIN dbo.CORSODILAUREA AS RESPONSABILE_CDL 
    ON RESPONSABILE.COD_CDL = RESPONSABILE_CDL.CDL
INNER JOIN dbo.CITTA AS RESPONSABILE_CITTA 
    ON RESPONSABILE.RESIDENZA = RESPONSABILE_CITTA.CITTA
INNER JOIN dbo.DOCENTE AS DIRETTORE 
    ON LABORATORIO_DIPARTIMENTO.CF_DIRETTORE = DIRETTORE.CF
INNER JOIN dbo.CITTA AS DIRETTORE_CITTA 
    ON DIRETTORE.RESIDENZA = DIRETTORE_CITTA.CITTA
INNER JOIN dbo.CORSODILAUREA AS DIRETTORE_CDL 
    ON DIRETTORE.COD_CDL = DIRETTORE_CDL.CDL
LEFT OUTER JOIN dbo.RICERCATORE AS DIRETTORE_RICERCATORE 
    ON DIRETTORE.CF = DIRETTORE_RICERCATORE.CF
LEFT OUTER JOIN dbo.RICERCATORE AS RESPONSABILE_RICERCATORE 
    ON RESPONSABILE.CF = RESPONSABILE_RICERCATORE.CF
UNION 
SELECT	'NO_LAB','NO_LAB','NO_LAB','NO_LAB','NO_LAB',9999,'NO_LAB','NO_LAB','NO_LAB','NO_LAB','NO_LAB','NO_LAB','NO_LAB',9999,
		'NO_LAB','NO_LAB','NO_LAB','NO_LAB','NO_LAB','NO_LAB'


