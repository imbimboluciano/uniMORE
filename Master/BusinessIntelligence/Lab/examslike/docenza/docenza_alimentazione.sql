-- FACT TABLE
CREATE VIEW FACT_TABLE AS
SELECT	AA,COD_CDL_INSEGNAMENTO,CF_TITOLARE,COD_CDL_ESERCITATORE,COD_LAB,
		SOMMA_CFU = SUM(CFU), COUNT_CFU = COUNT(CFU),
		NUM_INSEGNAMENTI = COUNT(DISTINCT COD_INS),
		NUM_ESERCITATORE = COUNT(DISTINCT CF_ESERCITATORE)
FROM PER_FT
GROUP BY AA,COD_CDL_INSEGNAMENTO,CF_TITOLARE,COD_CDL_ESERCITATORE,COD_LAB


-- STAR SCHEMA VIRTUALE
CREATE VIEW STARSCHEMA AS
SELECT dbo.FACT_TABLE.AA, dbo.DT_DOCENTE.*, dbo.FACT_TABLE.SOMMA_CFU, dbo.FACT_TABLE.COUNT_CFU, dbo.FACT_TABLE.NUM_INSEGNAMENTI, dbo.FACT_TABLE.NUM_ESERCITATORE, 
                  dbo.FACT_TABLE.COD_CDL_ESERCITATORE, DT_CDL_1.TIPO AS COD_CDL_ESERCITATORE_TIPO, dbo.DT_CDL.TIPO AS COD_CDL_INSEGNAMENTO_TIPO, dbo.FACT_TABLE.COD_CDL_INSEGNAMENTO, dbo.DT_COD_LAB.*
FROM     dbo.DT_CDL AS DT_CDL_1 INNER JOIN
                  dbo.FACT_TABLE INNER JOIN
                  dbo.DT_DOCENTE ON dbo.FACT_TABLE.CF_TITOLARE = dbo.DT_DOCENTE.DOCENTE ON DT_CDL_1.CDL = dbo.FACT_TABLE.COD_CDL_ESERCITATORE INNER JOIN
                  dbo.DT_CDL ON dbo.FACT_TABLE.COD_CDL_INSEGNAMENTO = dbo.DT_CDL.CDL INNER JOIN
                  dbo.DT_COD_LAB ON dbo.FACT_TABLE.COD_LAB = dbo.DT_COD_LAB.LABORATORIO

SELECT * FROM STARSCHEMA
