CREATE VIEW FACT_TABLE_PD AS
SELECT DATA, TURNO, AZIENDA_PERSONALE, F.DIPARTIMENTO, AZIENDA_MACCHINA_PULITRICE,P.SEDE,
		-- Impatto
		NumUFFICI, -- VERSIONE NON PESATA
		NumUFFICI_PES = NumUFFICI * P.PESO, -- VERSIONE PESATA
		-- Pesata
		NumORE_PES = NumORE * P.PESO
FROM FACT_TABLE F INNER JOIN PESO P ON F.DIPARTIMENTO = P.DIPARTIMENTO

