-- NumITINERARI  NA = {RESIDENZA,ANNO}
-- NumViaggi DI IMPATTO
CREATE VIEW SQL_OLAP AS
SELECT	RESIDENZA, ANNO, SEDE,
		NumITINERARI = CASE 
							WHEN GROUPING(RESIDENZA) = 0 AND GROUPING(ANNO) = 0 THEN SUM(NumITINERARI_PES)
							ELSE -SUM(NumITINERARI_PES)
						END, 
		NumVIAGGI = CASE
						-- SE SEDE VERSIONE NON PESATA
						WHEN GROUPING(SEDE) = 0 THEN SUM(NumVIAGGI)
						ELSE SUM(NumVIAGGI_PES)
					END
FROM STARSCHEMA
GROUP BY RESIDENZA, ANNO, SEDE WITH CUBE


-- PATTERN VUOTO
SELECT * FROM SQL_OLAP
WHERE RESIDENZA IS NULL AND ANNO IS NULL AND SEDE IS NULL
-- NumVIAGGI GIUSTO MENTRE NumITINERARI NO PERCHE NON AGGREGABILE SU QUESTE DIMENSIONI


SELECT * FROM SQL_OLAP
WHERE RESIDENZA IS NOT NULL AND ANNO IS NULL AND SEDE IS NULL
ORDER BY 4 DESC

