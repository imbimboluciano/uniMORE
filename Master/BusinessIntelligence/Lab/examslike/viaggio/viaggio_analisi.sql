CREATE VIEW AGENZIA_PARTENZA_DESTINAZIONE AS
SELECT	AGENZIA, PARTENZA, DESTINAZIONE_STATO, 
		SUM(NumVIAGGI) AS NumVIAGGI
FROM STARSCHEMA
GROUP BY AGENZIA, PARTENZA, DESTINAZIONE_STATO WITH CUBE;


SELECT * FROM AGENZIA_PARTENZA_DESTINAZIONE

CREATE VIEW TOP_P2 AS
SELECT	AGENZIA, PARTENZA, DESTINAZIONE_STATO, NumVIAGGI,
		RANK() OVER (PARTITION BY AGENZIA ORDER BY NumVIAGGI DESC) AS [RANK]
FROM AGENZIA_PARTENZA_DESTINAZIONE

ALTER VIEW TOP_P2B AS
SELECT *,
		RANK() OVER (PARTITION BY AGENZIA ORDER BY RANK) as RANK2
FROM TOP_P2
WHERE (DESTINAZIONE_STATO IS NOT NULL AND PARTENZA IS NOT NULL OR (DESTINAZIONE_STATO IS NULL AND PARTENZA IS NULL AND AGENZIA IS NOT NULL))

SELECT * FROM TOP_P2B WHERE RANK <= 2



