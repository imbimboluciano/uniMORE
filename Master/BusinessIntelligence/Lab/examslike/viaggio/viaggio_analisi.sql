SELECT * FROM STARSCHEMA
-- si considerano le variabili (attributi dimensionali) in gioco, AGENZIA e PARTENZA_CITTA
-- con anche i totali parziali (WITH CUBE)

CREATE VIEW AGENZIA_PARTENZA AS
SELECT	AGENZIA, PARTENZA, 
		SUM(NumVIAGGI) AS NumVIAGGI
FROM STARSCHEMA
GROUP BY AGENZIA, PARTENZA WITH CUBE;


SELECT * FROM AGENZIA_PARTENZA

-- si effettua il ranking delle città (di partenza) rispetto alle agenzie sulla base di NumVIAGGI

-- è possibile usare ROW_NUMBER() o RANK(); usiamo quest'ultima per considerare anche i parimerito

ALTER VIEW TOP_P AS
SELECT	AGENZIA, PARTENZA, NumVIAGGI,
		RANK() OVER (PARTITION BY AGENZIA ORDER BY NumVIAGGI DESC) AS [RANK],
		( SUM (NumVIAGGI) OVER (PARTITION BY AGENZIA) ) / 2 AS TOTALEAGENZIA,
		100.0 * NumVIAGGI / (max (NumVIAGGI) OVER (PARTITION BY AGENZIA)) as RAPPORTO
FROM AGENZIA_PARTENZA

SELECT * 
FROM TOP_P 
WHERE RANK <=2


