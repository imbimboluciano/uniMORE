--STAR SCHEMA
CREATE VIEW STARSCHEMA AS
SELECT dbo.DT_RESIDENZA.RESIDENZA_DISTRETTO, dbo.DT_RESIDENZA.RESIDENZA_REGIONE, dbo.DT_RESIDENZA.RESIDENZA_REGIONE_STATO, dbo.DT_PARTENZA.PARTENZA_DISTRETTO, dbo.DT_PARTENZA.PARTENZA_REGIONE, 
                  dbo.DT_PARTENZA.PARTENZA_REGIONE_STATO, dbo.FT_PUSHDOWN.RESIDENZA, dbo.FT_PUSHDOWN.PARTENZA, dbo.FT_PUSHDOWN.DESTINAZIONE_STATO, dbo.FT_PUSHDOWN.ANNO, dbo.FT_PUSHDOWN.AGENZIA, 
                  dbo.FT_PUSHDOWN.SEDE, dbo.FT_PUSHDOWN.NumVIAGGI_PES, dbo.FT_PUSHDOWN.NumVIAGGI, dbo.FT_PUSHDOWN.NumITINERARI_PES, dbo.FT_PUSHDOWN.NumPERSONE_PES
FROM     dbo.FT_PUSHDOWN INNER JOIN
                  dbo.DT_RESIDENZA ON dbo.FT_PUSHDOWN.RESIDENZA = dbo.DT_RESIDENZA.RESIDENZA_CITTA INNER JOIN
                  dbo.DT_PARTENZA ON dbo.FT_PUSHDOWN.PARTENZA = dbo.DT_PARTENZA.PARTENZA_CITTA


SELECT * FROM STARSCHEMA



-- SNOWFLAKE SCHEMA

-- DIMENSION TABLE CITTA
CREATE VIEW SF_DT_CITTA AS
SELECT * FROM CITTA

-- DIMENSION TABLE REGIONE
CREATE VIEW SF_DT_REGIONE AS
SELECT * FROM REGIONE

-- SNOWFLAKE (DA SISTEMARE I NOMI)
CREATE VIEW SNOWFLAKE AS
SELECT dbo.FT_PUSHDOWN.ANNO, CITTA_PARTENZA.*, REGIONE_PARTENZA.STATO, CITTA_RESIDENZA.*, REGIONE_RESIDENZA.STATO AS Expr1, dbo.FT_PUSHDOWN.AGENZIA, dbo.FT_PUSHDOWN.DESTINAZIONE_STATO, 
                  dbo.FT_PUSHDOWN.SEDE, dbo.FT_PUSHDOWN.NumVIAGGI, dbo.FT_PUSHDOWN.NumVIAGGI_PES, dbo.FT_PUSHDOWN.NumITINERARI_PES, dbo.FT_PUSHDOWN.NumPERSONE_PES
FROM     dbo.SF_DT_REGIONE AS REGIONE_RESIDENZA INNER JOIN
                  dbo.SF_DT_CITTA AS CITTA_RESIDENZA ON REGIONE_RESIDENZA.REGIONE = CITTA_RESIDENZA.REGIONE INNER JOIN
                  dbo.FT_PUSHDOWN INNER JOIN
                  dbo.SF_DT_CITTA AS CITTA_PARTENZA ON dbo.FT_PUSHDOWN.PARTENZA = CITTA_PARTENZA.CITTA INNER JOIN
                  dbo.SF_DT_REGIONE AS REGIONE_PARTENZA ON CITTA_PARTENZA.REGIONE = REGIONE_PARTENZA.REGIONE ON CITTA_RESIDENZA.CITTA = dbo.FT_PUSHDOWN.RESIDENZA
