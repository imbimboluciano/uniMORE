
-- DIMENSION TABLE PARTENZA
CREATE VIEW DT_PARTENZA AS
SELECT PARTENZA.CITTA AS PARTENZA_CITTA, PARTENZA.DISTRETTO AS PARTENZA_DISTRETTO, dbo.REGIONE.REGIONE AS PARTENZA_REGIONE, dbo.REGIONE.STATO AS PARTENZA_REGIONE_STATO
FROM     dbo.CITTA AS PARTENZA INNER JOIN
                  dbo.REGIONE ON PARTENZA.REGIONE = dbo.REGIONE.REGIONE

SELECT COUNT(*) FROM DT_PARTENZA
SELECT COUNT(*) FROM CITTA


-- DIMENSION TABLE RESIDENZA
CREATE VIEW DT_RESIDENZA AS
SELECT RESIDENZA.CITTA AS RESIDENZA_CITTA, RESIDENZA.DISTRETTO AS RESIDENZA_DISTRETTO, dbo.REGIONE.REGIONE AS RESIDENZA_REGIONE, dbo.REGIONE.STATO AS RESIDENZA_REGIONE_STATO
FROM     dbo.CITTA AS RESIDENZA INNER JOIN
                  dbo.REGIONE ON RESIDENZA.REGIONE = dbo.REGIONE.REGIONE

SELECT COUNT(*) FROM DT_RESIDENZA
SELECT COUNT(*) FROM CITTA

-- VISTA APPOGGIO PER_FT
CREATE VIEW PER_FT AS
SELECT DISTINCT dbo.VIAGGIO.PERSONA, dbo.VIAGGIO.ITINERARIO, dbo.VIAGGIO.ANNO, dbo.ITINERARIO.PARTENZA, dbo.ITINERARIO.AGENZIA, dbo.PERSONA.RESIDENZA, dbo.REGIONE.STATO AS DESTINAZIONE_STATO
FROM     dbo.CITTA INNER JOIN
                  dbo.ITINERARIO ON dbo.CITTA.CITTA = dbo.ITINERARIO.DESTINAZIONE INNER JOIN
                  dbo.REGIONE ON dbo.CITTA.REGIONE = dbo.REGIONE.REGIONE INNER JOIN
                  dbo.VIAGGIO ON dbo.ITINERARIO.ITINERARIO = dbo.VIAGGIO.ITINERARIO INNER JOIN
                  dbo.PERSONA ON dbo.VIAGGIO.PERSONA = dbo.PERSONA.PERSONA

SELECT COUNT(*) FROM PER_FT
SELECT COUNT(*) FROM VIAGGIO


-- FACT TABLE VIAGGIO

CREATE VIEW FACT_TABLE AS 
SELECT	RESIDENZA, PARTENZA, DESTINAZIONE_STATO, ANNO, AGENZIA,
		NumVIAGGI = COUNT(*), NumITINERARI = COUNT(DISTINCT ITINERARIO),
		NumPERSONE = COUNT(DISTINCT PERSONA)
FROM PER_FT
GROUP BY RESIDENZA, PARTENZA, DESTINAZIONE_STATO, ANNO, AGENZIA


-- ARCO MULTIPLO
-- AGENZIA HA CON + SEDI
SELECT DISTINCT AGENZIA, 'X' AS SEDE, 1.0 AS PESO INTO PESO FROM ITINERARIO
UPDATE PESO SET PESO=0.5 WHERE AGENZIA = 'AGAT'
INSERT PESO SELECT 'AGAT','Y',0.5
SELECT * FROM PESO

-- FACT TABLE CON PUSHDOWN
CREATE VIEW FT_PUSHDOWN AS
SELECT	RESIDENZA, PARTENZA, DESTINAZIONE_STATO, ANNO, FACT_TABLE.AGENZIA,
-- ARCO MULTIPLO
PESO.SEDE,
-- MISURE 
--- IMPATTO (DUE VERSIONI)
		NumVIAGGI, -- NON PESATA
		NumVIAGGI_PES = NumVIAGGI * PESO.PESO, -- PESATA
--- PESATA 
		NumITINERARI_PES = NumITINERARI * PESO,
		NumPERSONE_PES = NumPERSONE * PESO
FROM FACT_TABLE JOIN PESO ON FACT_TABLE.AGENZIA = PESO.AGENZIA

