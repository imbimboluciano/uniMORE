

-- DIMENSION TABLE DIPENDENTE
CREATE VIEW DT_DIPENDENTE AS
SELECT 
    DIPENDENTE_DIPARTIMENTO_CITTA.CITTA AS DIPENDENTE_DIPARTIMENTO_CITTA,
    DIPENDENTE_DIPARTIMENTO_CITTA.REGIONE AS DIPENDENTE_DIPARTIMENTO_REGIONE,
    DIPENDENTE_DIPARTIMENTO.DIP AS DIPENDENTE_DIPARTIMENTO,
    DIPENDENTE_DIPARTIMENTO.GENERE AS DIPENDENTE_DIPARTIMENTO_GENERE,
    DIPENDENTE.CF AS DIPENDENTE_CF,
    DIPENDENTE.ETA AS DIPENDENTE_ETA,
    DIPENDENTE_CITTA.CITTA AS DIPENDENTE_CITTA,
    DIPENDENTE_CITTA.REGIONE AS DIPENDENTE_CITTA_REGIONE
FROM 
    dbo.CITTA AS DIPENDENTE_DIPARTIMENTO_CITTA
    INNER JOIN dbo.DIPARTIMENTO AS DIPENDENTE_DIPARTIMENTO 
        ON DIPENDENTE_DIPARTIMENTO_CITTA.CITTA = DIPENDENTE_DIPARTIMENTO.SEDE 
    INNER JOIN dbo.DIPENDENTE 
        ON DIPENDENTE_DIPARTIMENTO.DIP = DIPENDENTE.AFFERISCE_A 
    INNER JOIN dbo.CITTA AS DIPENDENTE_CITTA 
        ON DIPENDENTE.RESIDENZA = DIPENDENTE_CITTA.CITTA;

SELECT COUNT(*) FROM DT_DIPENDENTE
SELECT COUNT(*) FROM DIPENDENTE


