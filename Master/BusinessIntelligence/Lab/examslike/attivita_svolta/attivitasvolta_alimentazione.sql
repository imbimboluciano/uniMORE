-- VISTA APPOGGIO
CREATE VIEW PER_FT AS
SELECT dbo.ATTIVITASVOLTA.MESE, dbo.ATTIVITASVOLTA.SVOLTA_DA AS DIPENDENTE, dbo.ATTIVITASVOLTA.NORE, dbo.ATTIVITASVOLTA.COD_PROG AS PROGETTO, dbo.PROGETTO.PROPOSTO_DA AS DIPARTIMENTO_PROGETTO, 
                  COALESCE(dbo.EXTRA.TIPO,'NO_EXTRA') AS EXTRA_TIPO, COALESCE(dbo.REPARTO.REPARTO,'NO_EXTRA') AS EXTRA_REPARTO
FROM     dbo.PROGETTO INNER JOIN
                  dbo.ATTIVITASVOLTA ON dbo.PROGETTO.COD_PROG = dbo.ATTIVITASVOLTA.COD_PROG LEFT OUTER JOIN
                  dbo.REPARTO INNER JOIN
                  dbo.EXTRA ON dbo.REPARTO.REPARTO = dbo.EXTRA.SVOLTA_IN ON dbo.ATTIVITASVOLTA.MESE = dbo.EXTRA.MESE AND dbo.ATTIVITASVOLTA.COD_PROG = dbo.EXTRA.COD_PROG AND 
                  dbo.ATTIVITASVOLTA.NOMEATTIVITA = dbo.EXTRA.NOMEATTIVITA

SELECT COUNT(*) FROM ATTIVITASVOLTA
SELECT COUNT(*) FROM PER_FT

-- FACT TABLE
CREATE VIEW FACT_TABLE AS 
SELECT	MESE, DIPENDENTE, DIPARTIMENTO_PROGETTO, EXTRA_TIPO, EXTRA_REPARTO,
		SOMMA_NORE = SUM(NORE), COUNT_NORE = COUNT(NORE),
		NUM_PROGETTI = COUNT(DISTINCT PROGETTO)
FROM PER_FT
GROUP BY MESE, DIPENDENTE, DIPARTIMENTO_PROGETTO, EXTRA_TIPO, EXTRA_REPARTO

