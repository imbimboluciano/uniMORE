
-- Dimension Table Studente

DROP VIEW IF EXISTS DT_STUD

CREATE VIEW DT_STUD AS
SELECT  
    CONCAT(STUDENTE.MATR,'_',STUDENTE.CDL)  AS 'STUDENTE.STUD',    
    STUDENTE.SESSO AS 'STUDENTE.SESSO',  
    PERSONA.CF AS 'PERSONA.CF',  
    PERSONA.ETA AS 'PERSONA.ETA',  
    STUDENTE_CITTA.CITTA AS 'STUDENTE_CITTA.CITTA',  
    STUDENTE_CITTA.ALTIT AS 'STUDENTE_CITTA.ALTIT',  
    STUDENTE_REGIONE.REG AS 'STUDENTE_REGIONE.REG',  
    STUDENTE_REGIONE.STATO AS 'STUDENTE_REGIONE.STATO',  
    STUDENTE_REGIONE.CONT AS 'STUDENTE_REGIONE.CONT',  
    STUDENTE_REGIONE.CAPOL AS 'STUDENTE_REGIONE.CAPOL'  
FROM dbo.CITTA AS STUDENTE_CITTA  
INNER JOIN dbo.PER AS PERSONA  
    ON STUDENTE_CITTA.CITTA = PERSONA.CITTA  
INNER JOIN dbo.REG AS STUDENTE_REGIONE  
    ON STUDENTE_CITTA.REG = STUDENTE_REGIONE.REG  
INNER JOIN dbo.STUD AS STUDENTE  
    ON PERSONA.CF = STUDENTE.CF;  


