-- Fact Table

CREATE VIEW FACT_TABLE AS
SELECT MATR + '_' + CDL AS STUD, DOC, ANNO, COUNT(*) AS NUMESAMI, MAX(VOTO) AS MAXVOTO
FROM ESAME
GROUP BY MATR,CDL,DOC,ANNO


-- Star schema 

CREATE SCHEMA STARSCHEMA;

SELECT * INTO STARSCHEMA.FACT_TABLE FROM FACT_TABLE;
SELECT * INTO STARSCHEMA.DT_STUD FROM DT_STUD;
SELECT * INTO STARSCHEMA.DT_DOC FROM DT_DOC;


-- Snowflake schema

CREATE VIEW DT_CITTA AS SELECT * FROM CITTA
CREATE VIEW DT_REG AS SELECT REG, CAPOL, STATO FROM REG
CREATE VIEW DT_STATO AS SELECT DISTINCT STATO, CONT FROM REG

CREATE VIEW DT_DIP AS SELECT DISTINCT DIP FROM DOC


