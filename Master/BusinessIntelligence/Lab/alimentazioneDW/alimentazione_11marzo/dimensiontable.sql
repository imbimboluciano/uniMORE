-- Dimension Table Docente

CREATE VIEW DT_DOC AS
SELECT  
	CASE WHEN DOC_TECN.CF IS NOT NULL THEN 'S' ELSE 'N' END AS 'DOC_TECN_Y_N',
    COALESCE(DOC_TECN.SPEC,'NO_SPEC') AS 'DOC_TECN.SPEC',  
    DOC.CF AS 'DOC.CF',  
    DIP_CITTA.CITTA AS 'DIP_CITTA.CITTA',  
    DOC.DIP AS 'DOC.DIP',  
    DIP_CITTA.ALTIT AS 'DIP_CITTA.ALTIT',  
    DIP_REGIONE.REG AS 'DIP_REGIONE.REG',  
    DIP_REGIONE.STATO AS 'DIP_REGIONE.STATO',  
    DIP_REGIONE.CONT AS 'DIP_REGIONE.CONT',  
    DIP_REGIONE.CAPOL AS 'DIP_REGIONE.CAPOL',  
    DOCENTE_REGIONE.REG AS 'DOCENTE_REGIONE.REG',  
    DOCENTE_REGIONE.CONT AS 'DOCENTE_REGIONE.CONT',  
    DOCENTE_REGIONE.STATO AS 'DOCENTE_REGIONE.STATO',  
    DOCENTE_REGIONE.CAPOL AS 'DOCENTE_REGIONE.CAPOL',  
    DOCENTE_CITTA.CITTA AS 'DOCENTE_CITTA.CITTA',  
    DOCENTE_CITTA.ALTIT AS 'DOCENTE_CITTA.ALTIT',  
    PER.ETA AS 'PER.ETA',  
    PER.CF AS 'PER.CF'  
FROM dbo.REG AS DOCENTE_REGIONE  
INNER JOIN dbo.PER  
    INNER JOIN dbo.CITTA AS DOCENTE_CITTA  
        ON PER.CITTA = DOCENTE_CITTA.CITTA  
    INNER JOIN dbo.DOC  
        ON PER.CF = DOC.CF  
    ON DOCENTE_REGIONE.REG = DOCENTE_CITTA.REG  
INNER JOIN dbo.CITTA AS DIP_CITTA  
    ON DOC.DIP_CITTA = DIP_CITTA.CITTA  
INNER JOIN dbo.REG AS DIP_REGIONE  
    ON DIP_CITTA.REG = DIP_REGIONE.REG  
LEFT JOIN dbo.DOC_TECN  
    ON DOC.CF = DOC_TECN.CF;  


